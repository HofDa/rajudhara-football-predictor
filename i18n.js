const listeners = new Set();

function detect() {
  const stored = (() => { try { return localStorage.getItem(STORAGE_KEY); } catch { return null; } })();
  if (stored && strings[stored]) return stored;
  const preferred = (navigator.languages || [navigator.language || "de"]).map(tag => String(tag).slice(0, 2).toLowerCase());
  return preferred.find(code => strings[code]) || "de";
}

let current = detect();

export const language = () => current;
export const localeTag = () => LANGUAGES.find(item => item.code === current)?.locale || "de-DE";

export function t(key, params = {}) {
  const template = strings[current]?.[key] ?? strings.de[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function setLanguage(code) {
  if (!strings[code] || code === current) return;
  current = code;
  try { localStorage.setItem(STORAGE_KEY, code); } catch { /* storage full or blocked */ }
  applyTranslations();
  listeners.forEach(listener => listener(code));
}

export function onLanguageChange(listener) {
  listeners.add(listener);
}

export function applyTranslations(root = document) {
  document.documentElement.lang = current;
  root.querySelectorAll("[data-i18n]").forEach(element => { element.textContent = t(element.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(element => { element.innerHTML = t(element.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-label]").forEach(element => { element.setAttribute("aria-label", t(element.dataset.i18nLabel)); });
}

export const num = (value, digits = 2) => value !== null && value !== undefined && value !== "" && Number.isFinite(Number(value))
  ? new Intl.NumberFormat(localeTag(), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(Number(value))
  : "–";

export const signedNum = (value, digits = 2) => `${Number(value || 0) >= 0 ? "+" : ""}${num(Number(value || 0), digits)}`;

export const pct = value => Number.isFinite(value)
  ? `${new Intl.NumberFormat(localeTag(), { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(value * 100)} %`
  : "–";

export const money = value => value !== null && value !== undefined && value !== "" && Number.isFinite(Number(value))
  ? new Intl.NumberFormat(localeTag(), { style: "currency", currency: "EUR" }).format(Number(value))
  : "–";

export const marketLabel = market => t(`market.${market}`);
